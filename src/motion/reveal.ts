// Появление карточек блюд: задержка колонки.
//
// Карточки ряда появляются волной слева направо, шаг — stagger из настроек
// (docs/MOTION.md §2: 70 мс). Но не больше трёх шагов подряд: четвёртая
// колонка появляется вместе с третьей. Длинные каскады выглядят дёшево, и на
// широком экране последняя карточка ряда иначе ждала бы почти полсекунды.
//
// Отдельным модулем — чтобы это правило проверялось обычным тестом, а не
// глазами по четырём колонкам на макете.

/** Сколько колонок ещё ждут своей очереди: 0-я, 1-я, 2-я, дальше — как 2-я. */
export const MAX_DELAYED_COLUMNS = 2;

/**
 * Задержка появления карточки, мс.
 * @param column  номер колонки в сетке, считая с нуля слева
 * @param stagger шаг между колонками, мс (src/config/motion.json)
 */
export function revealDelay(column: number, stagger: number): number {
  if (!(column > 0) || !(stagger > 0)) return 0;
  return Math.min(Math.round(column), MAX_DELAYED_COLUMNS) * stagger;
}
