/** Неизвестная буква — с запасом, как самые широкие обычные (Ш, Ы). */
const FALLBACK = 0.8;

/** Ширина слова в em (1 = размер шрифта) при начертании вывески. */
export function billboardWidthEm(word: string): number {
  let sum = 0;
  for (const char of word.toUpperCase()) sum += WIDTHS[char] ?? FALLBACK;
  return Math.round(sum * 1000) / 1000;
}
